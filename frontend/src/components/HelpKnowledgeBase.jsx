export default function HelpKnowledgeBase() {
  const [query, setQuery] = useState("");
  const [openIdx, setOpenIdx] = useState(null);

  const filtered = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return KB;
    return KB.map((group) => ({
      ...group,
      items: group.items.filter(
        (it) =>
          it.symptom.toLowerCase().includes(q) ||
          it.solution.toLowerCase().includes(q)
      ),
    })).filter((group) => group.items.length > 0);
  }, [query]);

  return (
    <div className="kb">
      <p className="muted">
        Βρες το μήνυμα που σου εμφάνισε η εφαρμογή και δες τι σημαίνει και τι
        να κάνεις. Αν δεν βρίσκεις λύση, επικοινώνησε μαζί μας παρακάτω.
      </p>

      <input
        className="input"
        type="text"
        placeholder="Αναζήτηση σφάλματος (π.χ. «κάμερα», «κωδικοί», «internet»)…"
        value={query}
        onChange={(e) => setQuery(e.target.value)}
      />

      {filtered.length === 0 && (
        <p className="muted">Δεν βρέθηκε κάτι σχετικό — δοκίμασε άλλη λέξη ή επικοινώνησε μαζί μας.</p>
      )}

      <div className="kb-list">
        {filtered.map((group) => (
          <div key={group.category} className="kb-group">
            <h3 className="kb-category">{group.category}</h3>
            {group.items.map((it, i) => {
              const key = `${group.category}::${i}`;
              const isOpen = openIdx === key;
              return (
                <div key={key} className="kb-item">
                  <button
                    type="button"
                    className="kb-question"
                    onClick={() => setOpenIdx(isOpen ? null : key)}
                  >
                    <span>{isOpen ? "▾" : "▸"}</span> {it.symptom}
                  </button>
                  {isOpen && <p className="kb-answer">{it.solution}</p>}
                </div>
              );
            })}
          </div>
        ))}
      </div>
    </div>
  );
}
